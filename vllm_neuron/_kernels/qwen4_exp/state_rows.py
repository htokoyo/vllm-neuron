"""Rows of a 4-D state pool read by hardware-DGE DMAs on the Sync queue (``state_rows_tkg``).

``model_bf16._pool_rows_4d`` reads the GDN recurrent state ``[n, Hv, K, V]`` (fp32) one row per slot with
``index_select``. neuronx-cc lowers that dynamic-offset copy to software-DGE DMAs issued by GpSimd, the engine that also
issues every state-pool write (``_pool_write``, ``DMA_INDIRECT`` scatters, and their address arithmetic). GpSimd runs its
instruction stream in order, so the read's position among the writes is whatever the scheduler picked for that graph: in
the TP16 B=16 decode NEFF of the fused MoE prefetch kernel (a device profile) the read of each GDN layer ended 108 us
later than in the other graph and ``gdn_tkg`` waited for it (+5.8 ms per step over 35 layers; the same flip in the
1,024-bucket graph of another profile). In the instruction streams of those NEFFs, on physical core 0, the layer's own conv-state pool
write (32 DMAs, their address arithmetic, and their waits for the layer's conv window) sits before the read's last
instructions in every GDN layer; in a graph without the slowdown a median of 2 (CPU compiles: the same placement
in every decode graph tried with the index_select read).

This kernel copies ``pool[slots[r]]`` HBM -> HBM with one DMA per (row, program), the dynamic row offset taken from the
slot ids in SBUF (``scalar_offset``), descriptors generated by the hardware DGE of the Sync engine (``dge_mode.hwdge``,
``engine.sync``; the slot-id load is pinned to the Sync queue as well): no GpSimd instruction, so the read cannot be ordered
behind a pool write on GpSimd. The ``Hv`` heads of
the ``B`` rows (``B * Hv`` [K, V] blocks, as ``gdn_tkg``'s BH axis) are split over the LNC grid like ``gdn_tkg`` splits
them. A byte copy: ``rows == pool[slots]`` bit for bit, including NaN payloads (NKI simulator check, grid 1 and 2).
"""
from __future__ import annotations

import nki
import nki.isa as nisa
import nki.language as nl


@nki.jit
def state_rows_tkg(pool, slots):
    """pool [N, H, K, V] (HBM, any dtype), slots [B, 1] int32 (0 <= id < N) -> rows [B, H, K, V] (HBM), rows[r] = pool[slots[r]]."""
    N, H, K, V = pool.shape
    B = slots.shape[0]
    KV = K * V
    n_prgs = nl.num_programs(0)
    prg = nl.program_id(0)
    BH = B * H
    per = BH // n_prgs
    h0 = prg * per
    h1 = BH if prg == n_prgs - 1 else h0 + per  # the last program takes the remainder (as gdn_tkg)
    rows = nl.ndarray((B, H, K, V), dtype=pool.dtype, buffer=nl.shared_hbm)
    idx = nl.ndarray((1, B), dtype=nl.int32, buffer=nl.sbuf)
    # the slot ids on the Sync queue too: left to the compiler, this small static load went to GpSimd in some graphs (B=32 TP16:
    # 19 of 36 layers), and the read DMAs wait for it
    nisa.dma_copy(dst=idx, src=slots.ap(pattern=[[B, 1], [1, B]], offset=0), dge_mode=nisa.dge_mode.hwdge, engine=nisa.engine.sync)
    for r in range(B):
        a = max(h0, r * H)
        e = min(h1, (r + 1) * H)
        if a >= e:
            continue  # no head of row r in this program
        src = pool.ap(pattern=[[KV, e - a], [1, KV]], offset=(a - r * H) * KV,
                      scalar_offset=idx.ap(pattern=[[B, 1], [1, 1]], offset=r), indirect_dim=0)
        nisa.dma_copy(dst=rows.ap(pattern=[[KV, e - a], [1, KV]], offset=a * KV), src=src,
                      dge_mode=nisa.dge_mode.hwdge, engine=nisa.engine.sync)
    return rows
