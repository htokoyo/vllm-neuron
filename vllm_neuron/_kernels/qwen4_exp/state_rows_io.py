"""Per-request state-pool row I/O by hardware-DGE DMAs on the Sync queue, for pools of any rank.

``state_rows_write_tkg``: ``pool[slots[r]] = value[r]`` in place (the kernel returns ``pool``, so the framework aliases
the output to the operand: no copy of the pool). It replaces ``model_bf16._pool_write``'s per-row ``pool[w[j]] = v[j]``,
which neuronx-cc lowers to a software-DGE scatter issued by GpSimd: ~13 DMAs plus their address arithmetic per row and
pool, all serialized on GpSimd. In a TP=8 decode device profile (8-layer model, B=32 / B=64) those writes were the
largest component of the step: 6.4 / 13.8 ms of 26.7 / 60.6 ms, GpSimd 8.3 / 16.7 ms busy.

``state_rows_read_tkg``: ``rows[r] = pool[slots[r]]`` for any rank (``state_rows.state_rows_tkg`` is the 4-D form that
splits [H, K, V] blocks over the LNC grid); it replaces the flattened ``index_select`` of the 3-D conv / PLE pools
(``model_bf16._pool_rows``: GpSimd indirect DMAs, 2.9 / 5.1 ms of the same steps).

The write: one DMA per (row, program), split over the LNC grid as the producer of the values splits them (see the
kernel); the read: one DMA per (row, program), each row's elements split into one contiguous chunk per program. The
dynamic row offset comes from the slot ids in SBUF (``scalar_offset``), descriptors are generated by the hardware DGE
of the Sync engine. Byte copies: the pools are bit-identical to the torch forms (NKI simulator, grid 1 and 2). Rows whose slot
repeats (padding rows all write the write-only sink row) are written in queue order; nothing reads the sink.
"""
from __future__ import annotations

import nki
import nki.isa as nisa
import nki.language as nl


def _row_elems(t):
    n = 1
    for s in t.shape[1:]:
        n *= s
    return n


def _chunk(R):
    n_prgs = nl.num_programs(0)
    prg = nl.program_id(0)
    per = R // n_prgs
    c0 = prg * per
    c1 = R if prg == n_prgs - 1 else c0 + per
    return c0, c1


def _load_slots(slots, B):
    idx = nl.ndarray((1, B), dtype=nl.int32, buffer=nl.sbuf)
    nisa.dma_copy(dst=idx, src=slots.ap(pattern=[[B, 1], [1, B]], offset=0), dge_mode=nisa.dge_mode.hwdge,
                  engine=nisa.engine.sync)
    return idx


@nki.jit
def state_rows_write_tkg(pool, slots, value):
    """pool [N, ...] (HBM), slots [B, 1] int32 (0 <= id < N), value [B, ...] (pool's dtype, same row shape) ->
    pool (aliased), with pool[slots[r]] = value[r].

    Work split over the LNC grid like the producer of ``value`` splits it: the B * H leading blocks of a 4-D row
    ([H, K, V]: gdn_tkg / gdn_tkg_act / gdn_tkg_grp split their B * H heads in contiguous ranges, the last program
    taking the remainder), whole rows for other ranks. Each program then reads only the part of ``value`` that it
    wrote itself; splitting every row's elements instead made each program read bytes the other program's kernel had
    just written, and the device outputs were not deterministic."""
    B = slots.shape[0]
    H = pool.shape[1] if len(pool.shape) == 4 else 1
    R = _row_elems(pool)
    blk = R // H  # elements per block
    n_prgs = nl.num_programs(0)
    prg = nl.program_id(0)
    BH = B * H
    per = BH // n_prgs
    h0 = prg * per
    h1 = BH if prg == n_prgs - 1 else h0 + per
    idx = _load_slots(slots, B)
    for r in range(B):
        a = max(h0, r * H)
        e = min(h1, (r + 1) * H)
        if a >= e:
            continue  # no block of row r in this program
        dst = pool.ap(pattern=[[blk, e - a], [1, blk]], offset=(a - r * H) * blk,
                      scalar_offset=idx.ap(pattern=[[B, 1], [1, 1]], offset=r), indirect_dim=0)
        nisa.dma_copy(dst=dst, src=value.ap(pattern=[[blk, e - a], [1, blk]], offset=a * blk),
                      dge_mode=nisa.dge_mode.hwdge, engine=nisa.engine.sync)
    return pool


@nki.jit
def state_rows_read_tkg(pool, slots):
    """pool [N, ...] (HBM), slots [B, 1] int32 (0 <= id < N) -> rows [B, ...] (HBM), rows[r] = pool[slots[r]]."""
    R = _row_elems(pool)
    B = slots.shape[0]
    c0, c1 = _chunk(R)
    rows = nl.ndarray((B,) + tuple(pool.shape[1:]), dtype=pool.dtype, buffer=nl.shared_hbm)
    idx = _load_slots(slots, B)
    for r in range(B):
        src = pool.ap(pattern=[[R, 1], [1, c1 - c0]], offset=c0,
                      scalar_offset=idx.ap(pattern=[[B, 1], [1, 1]], offset=r), indirect_dim=0)
        nisa.dma_copy(dst=rows.ap(pattern=[[R, 1], [1, c1 - c0]], offset=r * R + c0), src=src,
                      dge_mode=nisa.dge_mode.hwdge, engine=nisa.engine.sync)
    return rows
